    @Test
    fun pointAtPutsTheWristOnItsTargetAtTheHold() {
        val tl = timeline(ScriptEvent(timeSec = 1f, act = "point_at", actTarget = "0.62,0.40", actIntensity = 1f))
        val p = VerbPlacement()   // portrait, pelvis at (0.5, 0.52), character scale 1
        val o = VerbOffsets()
        ActVerbModel.evaluate(tl, 2.0, p, ActingTargets.NONE, rest, o)    // u = 1.0 s: inside the hold
        assertTrue(o.active)
        val torso = (rest[0] + o.b[0]) * Math.PI / 180
        val sh = doubleArrayOf(0.22 * cos(torso), 0.22 * sin(torso))
        val up = Math.toRadians(rest[0] + (rest[2] + o.b[2]).toDouble())
        val fa = up + Math.toRadians((rest[3] + o.b[3]).toDouble())
        val wx = sh[0] + 0.12 * cos(up) + 0.10 * cos(fa)
        val wy = sh[1] + 0.12 * sin(up) + 0.10 * sin(fa)
        val s = p.scaleH()
        assertEquals((0.62 - p.rootX) * p.aspect / s, wx, 1e-6)
        assertEquals((0.40 - p.rootY) / s, wy, 1e-6)
        assertTrue("the left arm is untouched", o.b[4] == 0.0 && o.b[5] == 0.0)
        assertTrue("it looks toward the target (to the right)", o.gx > 0.0)
    }

