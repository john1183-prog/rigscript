    @Test
    fun aLaterLookReplacesAnEarlierOneWithoutAJump() {
        val tl = timeline(
            ScriptEvent(timeSec = 1f, act = "look_at", actTarget = "left"), ScriptEvent(timeSec = 2f, act = "look_at", actTarget = "right")
        )
        val o = VerbOffsets()
        var prevX = 0.0
        var maxStep = 0.0
        var t = 0.9
        while (t < 4.0) {
            ActVerbModel.evaluate(tl, t, VerbPlacement(), ActingTargets.NONE, rest, o)
            assertTrue("weights never exceed one: ${o.gw}", o.gw <= 1.0 + 1e-9)
            if (t > 0.95) maxStep = maxOf(maxStep, abs(o.gx - prevX))
            prevX = o.gx
            t += 1.0 / 240
        }
        assertTrue("no jump in the gaze (max step $maxStep): a saccade, 0.6 head radii in 0.18 s", maxStep < 0.025)
        ActVerbModel.evaluate(tl, 1.8, VerbPlacement(), ActingTargets.NONE, rest, o)
        assertTrue("holds the first look until the second starts", o.gx < -0.25)
        ActVerbModel.evaluate(tl, 2.6, VerbPlacement(), ActingTargets.NONE, rest, o)
        assertTrue("then looks to the second", o.gx > 0.25)
    }

