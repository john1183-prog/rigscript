    @Test
    fun theTwoBoneIkMatchesThePrototypeAndReachesItsTarget() {
        val out = DoubleArray(4)
        for (row in IK_REF) {
            val f = row.split(",").map { it.toDouble() }
            ActVerbModel.ikTwoBone(f[0], f[1], f[2], f[3], f[4], if (f[2] >= f[0]) 1 else -1, 0.12, 0.10, out)
            assertEquals("upper", f[5], out[0], 2e-6)
            assertEquals("fore", f[6], out[1], 2e-6)
        }
        // A reachable target is hit exactly (elbow down on either arm).
        for (side in intArrayOf(1, -1)) {
            val tx = 0.13 * side
            val ty = -0.30
            ActVerbModel.ikTwoBone(0.0, -0.22, tx, ty, -90.0, side, 0.12, 0.10, out)
            assertEquals(1.0, out[2], 0.0)
            val ua = Math.toRadians(out[0] - 90.0)
            val fa = Math.toRadians(out[0] - 90.0 + out[1])
            val wx = 0.12 * cos(ua) + 0.10 * cos(fa)
            val wy = -0.22 + 0.12 * sin(ua) + 0.10 * sin(fa)
            assertEquals(tx, wx, 1e-9)
            assertEquals(ty, wy, 1e-9)
        }
        // Out of reach: clamped just short of a locked elbow, pointing at the target.
        ActVerbModel.ikTwoBone(0.0, -0.22, 0.9, -0.22, -90.0, 1, 0.12, 0.10, out)
        assertEquals(0.0, out[2], 0.0)
        val ua = Math.toRadians(out[0] - 90.0)
        val fa = Math.toRadians(out[0] - 90.0 + out[1])
        val reach = hypot(0.12 * cos(ua) + 0.10 * cos(fa), 0.12 * sin(ua) + 0.10 * sin(fa))
        assertEquals(0.22 * 0.98, reach, 1e-9)
    }

