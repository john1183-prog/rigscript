    @Test
    fun everyVerbReturnsToTheBasePoseExactlyAndStaysSmall() {
        for (name in ActVocabulary.VERBS) {
            val target = if (ActVocabulary.needsTarget(name)) "0.8,0.3" else null
            val tl = timeline(ScriptEvent(timeSec = 1f, act = name, actTarget = target, actIntensity = 1f))
            assertEquals(name, 1, tl.size)
            val p = VerbPlacement()
            val o = VerbOffsets()
            var worst = 0.0
            var t = 0.0
            while (t < 4.0) {
                ActVerbModel.evaluate(tl, t, p, ActingTargets.NONE, rest, o)
                for (v in o.b) { assertTrue("$name finite", v.isFinite()); worst = maxOf(worst, abs(v)) }
                assertTrue("$name face finite", (o.eyeH + o.eyeR + o.gx + o.gy + o.browH + o.browL + o.mouthW + o.mouthB + o.laugh).isFinite())
                t += 1.0 / 240
            }
            assertTrue("$name stays small (is $worst)", worst < (if (name == "point_at") 200.0 else 25.0))
            for (tt in doubleArrayOf(0.0, 0.99, 3.4, 3.9)) {
                ActVerbModel.evaluate(tl, tt, p, ActingTargets.NONE, rest, o)
                val sum = o.b.sumOf { abs(it) } + abs(o.eyeH) + abs(o.eyeR) + abs(o.gx) + abs(o.gy) + abs(o.browH) + abs(o.browL) + abs(o.mouthW) + abs(o.mouthB) + o.laugh
                assertEquals("$name is back at the base pose at t=$tt", 0.0, sum, 1e-9)
            }
        }
    }

